    if (rows.length === 0) {
        showToast('⚠️ Нет данных для формирования отчёта');
        return;
    }

    const summaryMap = {};

    rows.forEach(r => {
        const name = (r.name || 'Оборудование').trim();
        const cond = (r.condition || 'Исправен (в рабочем состоянии)').toLowerCase();

        let statusKey = 'Исправен';
        if (cond.includes('неисправен') || cond.includes('ремонт') || cond.includes('непригоден')) {
            statusKey = 'Неисправен';
        }

        if (!summaryMap[name]) {
            summaryMap[name] = { name: name, working: 0, broken: 0, total: 0 };
        }

        if (statusKey === 'Исправен') {
            summaryMap[name].working += 1;
        } else {
            summaryMap[name].broken += 1;
        }
        summaryMap[name].total += 1;
    });

    const summaryList = Object.values(summaryMap);
    let totalWorking = summaryList.reduce((acc, item) => acc + item.working, 0);

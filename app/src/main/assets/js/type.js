function openEditor(index) {
    if (!photos[index]) return;
    closeAllModals();
    editingIndex = index;
    editorImage.src = photos[index];
    editorModal.style.display = 'flex';
    setTimeout(function () {
        if (typeof Cropper === 'undefined') return;
        cropper = new Cropper(editorImage, {
            viewMode: 1, dragMode: 'move', autoCropArea: 1,
            background: false, responsive: true, checkOrientation: true,
            guides: true, center: true, highlight: false,
            cropBoxMovable: true, cropBoxResizable: true,
            toggleDragModeOnDblclick: false, zoomOnTouch: true, zoomOnWheel: true
        });
    }, 150);
}
function closeEditor() {
    if (cropper) { cropper.destroy(); cropper = null; }
    editorModal.style.display = 'none';
    editingIndex = -1;
}


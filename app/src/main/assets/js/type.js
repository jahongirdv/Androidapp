function performDeviceSearch() {
    const serialVal = (document.getElementById('searchSerialInput')?.value || '').trim().toLowerCase();
    const invVal = (document.getElementById('searchInventoryInput')?.value || '').trim().toLowerCase();
    const clsVal = (document.getElementById('searchClassification')?.value || '').trim().toLowerCase();
    const secVal = (document.getElementById('searchSection')?.value || '').trim().toLowerCase();
    const ptVal = (document.getElementById('searchPoint')?.value || '').trim().toLowerCase();
    const regVal = (document.getElementById('searchRegion')?.value || '').trim().toLowerCase();
    const distVal = (document.getElementById('searchDistrict')?.value || '').trim().toLowerCase();
    const orgVal = (document.getElementById('searchOrganization')?.value || '').trim().toLowerCase();
    const respVal = (document.getElementById('searchResponsible')?.value || '').trim().toLowerCase();
    const condVal = (document.getElementById('searchCondition')?.value || '').trim().toLowerCase();
    const uzasboVal = (document.getElementById('searchUzasboInput')?.value || '').trim().toLowerCase();

    const allRows = window.EQUIPMENT_CSV_ROWS || [];

    activeFilteredDevices = allRows.filter(r => {
        if (serialVal && (!r.serial_number || !r.serial_number.toLowerCase().includes(serialVal))) return false;
        if (invVal && (!r.inventory_number || !r.inventory_number.toLowerCase().includes(invVal))) return false;
        if (clsVal && (!r.classification || !r.classification.toLowerCase().includes(clsVal))) return false;
        if (secVal && (!r.classification_section || !r.classification_section.toLowerCase().includes(secVal))) return false;
        if (ptVal && (!r.classification_point || !r.classification_point.toLowerCase().includes(ptVal))) return false;
        if (regVal && (!r.region || !r.region.toLowerCase().includes(regVal))) return false;
        if (distVal && (!r.district || !r.district.toLowerCase().includes(distVal))) return false;
        if (orgVal && (!r.organization_name || !r.organization_name.toLowerCase().includes(orgVal))) return false;
        if (respVal && (!r.responsible_person || !r.responsible_person.toLowerCase().includes(respVal))) return false;
        if (condVal && (!r.condition || !r.condition.toLowerCase().includes(condVal))) return false;
        if (uzasboVal && (!r.uzasbo_number || !r.uzasbo_number.toLowerCase().includes(uzasboVal))) return false;
        return true;
    });

    renderDevicesTable(1);

    // Скроллим к таблице
    const tableSec = document.querySelector('.device-table-section');
    if (tableSec) {
        tableSec.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }

    if (activeFilteredDevices.length > 0) {
        showToast(`🔍 Найдено устройств: ${activeFilteredDevices.length}. Нажмите на строку в таблице, чтобы войти в форму изменения.`);
    } else {
        showToast('⚠️ По вашему запросу ничего не найдено.');
    }
}

let currentEditingDeviceId = null;

function fillEditForm(item) {
    if (!item) return;
    currentEditingDeviceId = item.id || null;

    if (item.classification) {
        const clsEl = document.getElementById('classificationInput');
        if (clsEl) clsEl.value = item.classification;
    }
    if (item.classification_section || item.section) {
        const secEl = document.getElementById('sectionInput');
        if (secEl) secEl.value = item.classification_section || item.section || '';
    }
    if (item.classification_point || item.point) {
        const ptEl = document.getElementById('pointInput');
        if (ptEl) ptEl.value = item.classification_point || item.point || '';
    }
    const firmEl = document.getElementById('firmInput');
    if (firmEl) firmEl.value = '';
    if (item.firm_country || item.country) {
        const fcEl = document.getElementById('firmCountrySelect');
        if (fcEl) {
            const countryVal = item.firm_country || item.country || 'Uzbekistan';
            let found = false;
            for (let i = 0; i < fcEl.options.length; i++) {
                if (fcEl.options[i].value.toLowerCase() === countryVal.toLowerCase()) {
                    fcEl.selectedIndex = i;
                    found = true;
                    break;
                }
            }
            if (!found && countryVal) {
                const opt = new Option(countryVal, countryVal);
                fcEl.add(opt);
                fcEl.value = countryVal;
            }
        }
    }
    if (item.country) {
        const cEl = document.getElementById('countryInput');
        if (cEl) {
            let found = false;
            for (let i = 0; i < cEl.options.length; i++) {
                if (cEl.options[i].value.toLowerCase() === item.country.toLowerCase()) {
                    cEl.selectedIndex = i;
                    found = true;
                    break;
                }
            }
            if (!found && item.country) {
                const opt = new Option(item.country, item.country);
                cEl.add(opt);
                cEl.value = item.country;
            }
        }
    }
    if (item.name) {
        const nameEl = document.getElementById('equipmentName');
        if (nameEl) nameEl.value = item.name;
    }
    if (item.model) {
        const modelEl = document.getElementById('modelInput');
        if (modelEl) modelEl.value = item.model;
    }
    if (item.serial_number || item.serial) {
        const serialEl = document.getElementById('serialInput');
        if (serialEl) serialEl.value = item.serial_number || item.serial || '';
    }
    if (item.inventory_number || item.inventory) {
        const invEl = document.getElementById('inventoryInput');
        if (invEl) invEl.value = item.inventory_number || item.inventory || '';
    }
    if (item.uzasbo_number || item.uzasbo_name || item.name) {
        const uzNameEl = document.getElementById('uzasboNameInput');
        if (uzNameEl) uzNameEl.value = item.uzasbo_number || item.uzasbo_name || item.name || '';
    }

    // Загрузка фото в превью
    photos = [];
    if (item.photos && Array.isArray(item.photos)) {
        photos = [...item.photos];
    } else if (item.photo_url) {
        photos = [item.photo_url];
    } else if (item.image) {
        photos = [item.image];
    }
    renderThumbnails();

    // Плавный скролл к форме изменения
    const formSec = document.querySelector('.form-section');
    if (formSec) {
        formSec.scrollIntoView({ behavior: 'smooth', block: 'start' });
        formSec.style.transition = 'box-shadow 0.4s ease, border-color 0.4s ease';
        formSec.style.borderColor = '#4d94e8';
        formSec.style.boxShadow = '0 0 28px rgba(77, 148, 232, 0.4)';
        setTimeout(() => {
            formSec.style.borderColor = 'rgba(255,255,255,0.05)';
            formSec.style.boxShadow = 'none';
        }, 2500);
    }
}


async function saveCurrentDevice() {
    const name = document.getElementById('equipmentName')?.value || '';
    const model = document.getElementById('modelInput')?.value || '';
    const inventory = document.getElementById('inventoryInput')?.value || '';
    const serial = document.getElementById('serialInput')?.value || '';
    const classification = document.getElementById('classificationInput')?.value || '';
    const section = document.getElementById('sectionInput')?.value || '';
    const point = document.getElementById('pointInput')?.value || '';
    const manufacturer = document.getElementById('firmInput')?.value || '';
    const firmCountry = document.getElementById('firmCountrySelect')?.value || '';
    const country = document.getElementById('countryInput')?.value || '';
    const uzasboName = document.getElementById('uzasboNameInput')?.value || '';

    if (!name && !inventory) {
        alert('Пожалуйста, заполните наименование оборудования или инвентарный номер.');
        return;
    }

    const deviceData = {
        id: currentEditingDeviceId || ('item_' + Date.now()),
        name: name,
        model: model,
        inventory_number: inventory,
        serial_number: serial,
        classification: classification,
        classification_section: section,
        classification_point: point,
        manufacturer: manufacturer,
        firm_country: firmCountry,
        country: country,
        uzasbo_name: uzasboName,
        photos: [...photos],
        updated_at: new Date().toISOString()
    };

    if (window.SUPABASE_URL && window.SUPABASE_KEY) {
        try {
            const method = currentEditingDeviceId && !currentEditingDeviceId.toString().startsWith('temp_') ? 'PATCH' : 'POST';
            let url = `${window.SUPABASE_URL}/rest/v1/equipment_items`;
            if (method === 'PATCH') {
                url += `?id=eq.${currentEditingDeviceId}`;
            }
            await fetch(url, {
                method: method,
                headers: {
                    'apikey': window.SUPABASE_KEY,
                    'Authorization': `Bearer ${window.SUPABASE_KEY}`,
                    'Content-Type': 'application/json',
                    'Prefer': 'return=representation'
                },
                body: JSON.stringify(deviceData)
            });
        } catch (e) {
            console.warn('⚠️ Ошибка сохранения в Supabase:', e);
        }
    }

    if (!window.EQUIPMENT_CSV_ROWS) window.EQUIPMENT_CSV_ROWS = [];
    const idx = window.EQUIPMENT_CSV_ROWS.findIndex(r => r.id === deviceData.id || (inventory && r.inventory_number === inventory));
    if (idx >= 0) {
        window.EQUIPMENT_CSV_ROWS[idx] = { ...window.EQUIPMENT_CSV_ROWS[idx], ...deviceData };
    } else {
        window.EQUIPMENT_CSV_ROWS.unshift(deviceData);
    }

    localStorage.setItem('jixozmed_equipment_items_cache', JSON.stringify(window.EQUIPMENT_CSV_ROWS));

    showToast('✅ Успешно сохранено!');
    initEquipmentTableData();
    backToList();
}


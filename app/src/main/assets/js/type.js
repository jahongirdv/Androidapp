function transformPhoto(rotateDeg, flipH) {
    return new Promise(function (resolve) {
        const img = new Image();
        img.onload = function () {
            const is90 = (Math.abs(rotateDeg) % 180 === 90);
            const w = is90 ? img.height : img.width;
            const h = is90 ? img.width : img.height;
            const c = document.createElement('canvas');
            c.width = w; c.height = h;
            const ctx = c.getContext('2d');
            ctx.translate(w / 2, h / 2);
            ctx.rotate(rotateDeg * Math.PI / 180);
            if (flipH) ctx.scale(-1, 1);
            ctx.drawImage(img, -img.width / 2, -img.height / 2);
            resolve(c.toDataURL('image/jpeg', JPEG_QUALITY));
        };
        img.src = photos[viewerCurrentIndex];
    });
}


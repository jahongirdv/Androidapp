function findEquipment() {
    const c = document.getElementById('classificationInput');
    const s = document.getElementById('sectionInput');
    const p = document.getElementById('pointInput');
    const list = document.getElementById('suggestionsList');
    const q = equipmentInput.value.trim().toLowerCase();
    if (list) { list.style.display = 'none'; list.innerHTML = ''; }
    if (!q) { if (c) c.value = ''; if (s) s.value = ''; if (p) p.value = ''; return; }

    const matches = [];
    for (const [key, value] of Object.entries(equipmentDatabase)) {
        if (key.includes(q) || q.includes(key)) {
            matches.push({ key: key, section: value.section, point: value.point });
        }
    }
    if (matches.length === 0) { if (c) c.value = ''; if (s) s.value = ''; if (p) p.value = ''; return; }
    if (matches.length === 1) { fillClassification(matches[0]); return; }
    showSuggestions(matches);
}

function fillClassification(m) {
    const c = document.getElementById('classificationInput');
    const s = document.getElementById('sectionInput');
    const p = document.getElementById('pointInput');
    if (c) c.value = m.section;
    if (s) s.value = m.point;
    if (p) p.value = m.key;
}

function showSuggestions(matches) {
    const list = document.getElementById('suggestionsList');
    if (!list) return;
    list.innerHTML = '';
    list.style.display = 'block';

    const header = document.createElement('div');
    header.className = 'suggestions-header';
    header.textContent = '🔍 Найдено ' + matches.length + '. Выберите:';
    list.appendChild(header);

    matches.forEach(function (m) {
        const item = document.createElement('div');
        item.className = 'suggestion-item';
        item.innerHTML = '<div class="suggestion-name">' + m.key + '</div>' +
            '<div class="suggestion-class"><span class="suggestion-section">' + m.section + '</span>' +
            '<span class="suggestion-point">' + m.point + '</span></div>';
        item.addEventListener('click', function () {
            equipmentInput.value = m.key;
            fillClassification(m);
            list.style.display = 'none';
        });
        list.appendChild(item);
    });
}

function showModelSuggestions() {
    const list = document.getElementById('modelSuggestionsList');
    const q = modelInput.value.trim().toLowerCase();
    if (!list || !q) { if (list) list.style.display = 'none'; return; }

    const matches = modelsDatabase.filter(function (item) {
        return item.model.toLowerCase().includes(q) || q.includes(item.model.toLowerCase());
    });
    if (matches.length === 0) { list.style.display = 'none'; return; }

    list.innerHTML = '';
    list.style.display = 'block';

    const header = document.createElement('div');
    header.className = 'suggestions-header';
    header.textContent = '🔍 Найдено ' + matches.length + ' моделей:';
    list.appendChild(header);

    matches.forEach(function (m) {
        const item = document.createElement('div');
        item.className = 'suggestion-item';
        item.innerHTML = '<div class="suggestion-name">' + m.model + '</div>' +
            '<div class="suggestion-class"><span class="suggestion-section">' + m.manufacturer + '</span>' +
            '<span class="suggestion-point">' + m.country + '</span></div>';
        item.addEventListener('click', function () {
            const eq = document.getElementById('equipmentName');
            const wasFilled = eq.value.trim() !== '';
            modelInput.value = m.model;
            document.getElementById('firmInput').value = m.manufacturer;
            document.getElementById('countryInput').value = m.country;
            if (!wasFilled && m.equipment) {
                eq.value = m.equipment;
                setTimeout(findEquipment, 100);
            }
            list.style.display = 'none';
        });
        list.appendChild(item);
    });
}

function findModel() {
    const fi = document.getElementById('firmInput');
    const ci = document.getElementById('countryInput');
    const eq = document.getElementById('equipmentName');
    const q = modelInput.value.trim().toLowerCase();
    if (!q) { fi.value = ''; ci.value = ''; return; }
    for (const item of modelsDatabase) {
        if (item.model.toLowerCase() === q) {
            const wasFilled = eq.value.trim() !== '';
            fi.value = item.manufacturer;
            ci.value = item.country;
            if (!wasFilled && item.equipment) {
                eq.value = item.equipment;
                setTimeout(findEquipment, 100);
            }
            return;
        }
    }
    fi.value = '';
    ci.value = '';
}


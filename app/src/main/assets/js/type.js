function compressImage(file, callback) {
    const reader = new FileReader();
    reader.onload = function (e) {
        const img = new Image();
        img.onload = function () {
            let w = img.width, h = img.height;
            if (w > h && w > MAX_IMAGE_SIZE) {
                h = Math.round(h * MAX_IMAGE_SIZE / w);
                w = MAX_IMAGE_SIZE;
            } else if (h > MAX_IMAGE_SIZE) {
                w = Math.round(w * MAX_IMAGE_SIZE / h);
                h = MAX_IMAGE_SIZE;
            }
            const c = document.createElement('canvas');
            c.width = w; c.height = h;
            c.getContext('2d').drawImage(img, 0, 0, w, h);
            callback(c.toDataURL('image/jpeg', JPEG_QUALITY));
        };
        img.src = e.target.result;
    };
    reader.readAsDataURL(file);
}

function addPhoto(file) {
    if (!file) return;
    compressImage(file, function (u) {
        photos.push(u);
        renderThumbnails();
    });
}

// ===== МИНИАТЮРЫ =====
function renderThumbnails() {
    if (!thumbnails) return;
    thumbnails.innerHTML = '';
    photos.forEach(function (dataUrl, index) {
        const div = document.createElement('div');
        div.className = 'thumbnail';
        div.style.cursor = 'pointer';

        const img = document.createElement('img');
        img.src = dataUrl;
        img.style.pointerEvents = 'none';
        div.appendChild(img);

        div.addEventListener('click', function (e) {
            e.preventDefault();
            e.stopPropagation();
            openViewer(index);
        });

        thumbnails.appendChild(div);
    });
}

